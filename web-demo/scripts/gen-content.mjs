// Generates src/rules/content/schema.gen.ts from the Kotlin content classes
// in core/rules/src/main/kotlin/com/pathways/rules/content: one TS interface
// per @Serializable class, and the schema the TS decoder reads (field types,
// JSON names, defaults, code serializers, enum spellings). Run it after a
// content class changes; the content parity vectors fail until you do.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const dir = path.resolve(here, '../../core/rules/src/main/kotlin/com/pathways/rules/content')
const out = path.resolve(here, '../src/rules/content/schema.gen.ts')

const strip = (s) => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/[^\n]*/g, '')

function closing(s, open) {
  let depth = 0
  for (let i = open; i < s.length; i++) {
    const c = s[i]
    if (c === '(' || c === '<' || c === '{' || c === '[') depth++
    else if (c === ')' || c === '>' || c === '}' || c === ']') {
      if (s[i - 1] === '-' && c === '>') continue
      depth--
      if (depth === 0) return i
    }
    else if (c === '"') { i = s.indexOf('"', i + 1) }
  }
  throw new Error('unbalanced')
}

function splitTop(s) {
  const parts = []
  let depth = 0, start = 0
  for (let i = 0; i < s.length; i++) {
    const c = s[i]
    if (c === '"') { i = s.indexOf('"', i + 1); continue }
    if ('(<{['.includes(c)) depth++
    else if (')}]'.includes(c) || (c === '>' && s[i - 1] !== '-')) depth--
    else if (c === ',' && depth === 0) { parts.push(s.slice(start, i)); start = i + 1 }
  }
  parts.push(s.slice(start))
  return parts.map((p) => p.trim()).filter(Boolean)
}

const classes = {}
const enums = {}
for (const f of fs.readdirSync(dir).filter((f) => f.endsWith('.kt'))) {
  const src = strip(fs.readFileSync(path.join(dir, f), 'utf8'))
  for (const m of src.matchAll(/data class (\w+)(?:<[^>]*>)?\(/g)) {
    const open = m.index + m[0].length - 1
    const body = src.slice(open + 1, closing(src, open))
    const fields = []
    for (const p of splitTop(body)) {
      const fm = /^((?:@[\w.]+(?:\([^)]*\))?\s*)*)(?:override\s+)?val\s+(\w+)\s*:\s*([^=]+?)(?:\s*=\s*([\s\S]+))?$/.exec(p)
      if (!fm) throw new Error(`${m[1]}: cannot read parameter "${p}"`)
      const [, ann, name, type, dflt] = fm
      const field = { name, type: type.trim().replace(/\s+/g, ' ') }
      const sn = /@SerialName\("([^"]+)"\)/.exec(ann)
      if (sn) field.json = sn[1]
      if (/ControllingAttributeCodeSerializer/.test(ann)) field.code = 'attr'
      if (/DifficultyCodeSerializer/.test(ann)) field.code = 'difficulty'
      if (dflt !== undefined) field.default = literal(dflt.trim(), `${m[1]}.${name}`)
      fields.push(field)
    }
    classes[m[1]] = fields
  }
  for (const m of src.matchAll(/enum class (\w+)(\([^)]*\))?\s*\{/g)) {
    const open = m.index + m[0].length - 1
    const body = src.slice(open + 1, closing(src, open)).split(';')[0]
    const spellings = {}
    for (const e of splitTop(body)) {
      const em = /^(?:@SerialName\("([^"]+)"\)\s*)?(\w+)/.exec(e)
      spellings[em[1] ?? em[2]] = em[2]
    }
    enums[m[1]] = spellings
  }
}

function literal(s, where) {
  if (s === 'null' || s === 'true' || s === 'false' || /^-?\d+(\.\d+)?$/.test(s)) return JSON.parse(s)
  if (/^"[^"$]*"$/.test(s)) return JSON.parse(s)
  if (/^(emptyList|listOf|emptySet|setOf)(<[^>]*>)?\(\)$/.test(s)) return []
  if (/^(emptyMap|mapOf)(<[^>]*>)?\(\)$/.test(s)) return {}
  throw new Error(`${where}: default "${s}" is not a literal this script reads`)
}

function tsType(t) {
  t = t.replace(/\b(?:[a-z]\w*\.)+([A-Z]\w*)/g, '$1')
  const nullable = t.endsWith('?')
  const base = nullable ? t.slice(0, -1) : t
  let ts
  const g = /^(\w+)<(.+)>$/.exec(base)
  if (g) {
    const args = splitTop(g[2])
    if (['List', 'Set', 'Collection'].includes(g[1])) ts = `${wrap(tsType(args[0]))}[]`
    else if (g[1] === 'Map') ts = `Record<string, ${tsType(args[1])}>`
    else ts = `${g[1]}<${args.map(tsType).join(', ')}>`
  } else {
    ts = { String: 'string', Int: 'number', Long: 'number', Double: 'number', Boolean: 'boolean' }[base] ?? base
  }
  return nullable ? `${ts} | null` : ts
}
const wrap = (t) => (t.includes('|') ? `(${t})` : t)

let ts = '// GENERATED by scripts/gen-content.mjs from the Kotlin content classes. Do not edit.\n'
ts += "import type { ControllingAttribute, Difficulty, DiceExpr } from '../model'\n\n"
for (const [name, spellings] of Object.entries(enums)) {
  ts += `export type ${name} = ${Object.values(spellings).map((v) => `'${v}'`).join(' | ')}\n`
}
ts += '\n'
for (const [name, fields] of Object.entries(classes)) {
  const generic = name === 'ContentFile' ? '<T>' : ''
  ts += `export interface ${name}${generic} {\n`
  for (const f of fields) ts += `  ${f.name}: ${f.name === 'entries' && generic ? 'T[]' : tsType(f.type)}\n`
  ts += '}\n\n'
}
ts += `export const ENUMS: Record<string, Record<string, string>> = ${JSON.stringify(enums, null, 2)}\n\n`
ts += `export interface FieldSchema { name: string; type: string; json?: string; code?: string; default?: unknown }\n\n`
ts += `export const SCHEMA: Record<string, FieldSchema[]> = ${JSON.stringify(classes, null, 2)}\n`

// ContentLoader's lazies: which file, which class, and how it is unwrapped.
const loaderSrc = strip(fs.readFileSync(path.join(dir, 'ContentLoader.kt'), 'utf8'))
const loaders = {}
for (const m of loaderSrc.matchAll(/val (\w+)Lazy\s*:\s*([^\n]+?)\s+by lazy\s*\{([\s\S]*?)(?=\n\s*(?:private val|fun |\}))/g)) {
  const [, lazy, declared, body] = m
  const file = /"([\w.]+\.json)"/.exec(body)[1]
  const whole = /loadWhole/.test(body)
  const typed = /load<(\w+)>/.exec(body)
  const listOf = /^List<(\w+)>$/.exec(declared)
  const cls = typed?.[1] ?? listOf?.[1] ?? declared
  const sort = /sortedBy \{ it\.(\w+) \}/.exec(body)?.[1]
  const mode = whole ? 'whole' : /\.single\(\)/.test(body) ? 'single' : /DamageRowJson/.test(body) ? 'thrustSwing' : 'entries'
  loaders[lazy] = { file, cls, mode, ...(sort ? { sort } : {}) }
}
const accessors = {}
for (const m of loaderSrc.matchAll(/fun (\w+)\(\)\s*:\s*[^=]+=\s*(\w+)Lazy(?:\.(\w+))?/g)) {
  accessors[m[1]] = { lazy: m[2], ...(m[3] ? { field: m[3] } : {}) }
}
ts += `\nexport const LOADERS: Record<string, { file: string; cls: string; mode: string; sort?: string }> = ${JSON.stringify(loaders, null, 2)}\n`
ts += `\nexport const ACCESSORS: Record<string, { lazy: string; field?: string }> = ${JSON.stringify(accessors, null, 2)}\n`
fs.mkdirSync(path.dirname(out), { recursive: true })
fs.writeFileSync(out, ts)
console.log(`${Object.keys(classes).length} classes, ${Object.keys(enums).length} enums -> ${path.relative(process.cwd(), out)}`)
