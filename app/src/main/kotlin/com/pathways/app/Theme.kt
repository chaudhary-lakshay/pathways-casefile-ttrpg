/**
 * The app's design system: one colour scheme, one type scale, one shape scale.
 *
 * The scheme is [CaseFile], GENERATED by `tools/gen_theme.py` into
 * [ThemeSchemes]; this file applies it. Case File replaced every preset, the
 * picker, dark mode, true black and Material You on the owner's ruling
 * (2026-10-17): one visual language, light only. The picker's history is in
 * git, and so is the reasoning that built it.
 */

// ---------------------------------------------------------------------------
// Type scale
// ---------------------------------------------------------------------------

/**
 * The scale is redefined here rather than at the call sites, and that is the
 * point of it.
 *
 * A census of the 16 UI files found **155 of 281** type calls (55%) using
 * `bodySmall`, whose Material default is 12sp -- the caption size. Only 8
 * used `bodyMedium`, the actual body size. At that ratio `bodySmall` is not
 * a deliberate caption choice repeated 155 times; it is the style the first
 * screen reached for and every later screen copied. So the fix is to make
 * the style readable, which is one file and no call-site diff, rather than
 * to rewrite 155 call sites and then review the result.
 *
 * The trade-off, stated because it is real: any genuinely deliberate caption
 * grows too. At 55% usage that is the minority case.
 *
 * Tracking is tighter than Material's defaults on the small sizes. Material
 * tracks small text loosely for glanceable labels; this app renders dense
 * tabular rules text, where loose tracking costs width the numbers need.
 */
private val PathwaysType = Typography().run {
    copy(
        // Body -- the reading sizes. bodySmall carries the app.
        bodySmall = bodySmall.copy(
            fontSize = 14.sp,
            lineHeight = 20.sp,
            letterSpacing = 0.15.sp,
        ),
        bodyMedium = bodyMedium.copy(
            fontSize = 15.sp,
            lineHeight = 21.sp,
            letterSpacing = 0.15.sp,
        ),
        bodyLarge = bodyLarge.copy(
            fontSize = 16.sp,
            lineHeight = 24.sp,
        ),
        // Titles -- row headers and dialog headings.
        titleSmall = titleSmall.copy(
            fontSize = 15.sp,
            lineHeight = 20.sp,
            fontWeight = FontWeight.SemiBold,
            letterSpacing = 0.sp,
        ),
        titleMedium = titleMedium.copy(
            fontSize = 17.sp,
            lineHeight = 24.sp,
            fontWeight = FontWeight.SemiBold,
            letterSpacing = 0.sp,
        ),
        titleLarge = titleLarge.copy(
            fontSize = 21.sp,
            lineHeight = 28.sp,
            fontWeight = FontWeight.SemiBold,
        ),
        headlineSmall = headlineSmall.copy(
            fontSize = 25.sp,
            lineHeight = 32.sp,
            fontWeight = FontWeight.SemiBold,
        ),
        // Labels -- buttons and chips.
        labelMedium = labelMedium.copy(fontSize = 13.sp, lineHeight = 17.sp),
        labelLarge = labelLarge.copy(fontSize = 15.sp, lineHeight = 20.sp),
    )
}

/**
 * A monospaced style for rolled totals and target numbers.
 *
 * ponytail: not part of the Material scale, because it answers a question the
 * scale does not ask -- "do these digits stay put when the number changes".
 * A plain val; promote to a CompositionLocal if a second theme ever varies it.
 */
val TabularNumerals: TextStyle
    @Composable get() = MaterialTheme.typography.titleMedium.copy(
        fontFamily = FontFamily.Monospace,
    )

/**
 * A number that changes in place: tabular digits, so a count does not
 * shift its neighbours as it changes. Every changing number goes through
 * here, so no screen asks which font is in play.
 */
fun TextStyle.tabular(): TextStyle = copy(fontFamily = FontFamily.Default, fontFeatureSettings = "tnum")

// ---------------------------------------------------------------------------
// Shape scale
// ---------------------------------------------------------------------------

/**
 * Rounder than Material's defaults, following the direction Material 3
 * Expressive took in 1.4. The Expressive entry points themselves
 * (`MaterialExpressiveTheme`) are deliberately not used: they are
 * `@ExperimentalMaterial3ExpressiveApi`, and opting in across 16 files buys
 * motion physics this app has no animation to spend it on.
 */
private val PathwaysShapes = Shapes(
    extraSmall = RoundedCornerShape(6.dp),
    small = RoundedCornerShape(10.dp),
    medium = RoundedCornerShape(14.dp),
    large = RoundedCornerShape(20.dp),
    extraLarge = RoundedCornerShape(28.dp),
)

// ---------------------------------------------------------------------------
// Paper
// ---------------------------------------------------------------------------

/**
 * How strongly the grain is drawn. `gen_theme.py` and `ThemeSchemesTest`
 * check every text colour through it, so raising it can fail AA: rerun both.
 */
internal const val GRAIN_ALPHA = 0.07f

/**
 * Washi grain laid OVER the content, not behind it: this app is almost all
 * opaque cards, which would hide a grain painted on the page. A 256 px
 * seamless tile generated for this app (fine noise plus blurred mottling),
 * so it carries no licence. Kept over the flat Case File frames on the
 * owner's ruling (2026-10-17).
 *
 * ponytail: drawn in the activity window only. A dialog is its own window
 * and stays flat; apply [paperGrain] in the shared dialog shells if that
 * difference shows.
 */
@Composable
fun Modifier.paperGrain(alpha: Float): Modifier {
    val tile = ImageBitmap.imageResource(R.drawable.paper_grain)
    val brush = remember(tile) { ShaderBrush(ImageShader(tile, TileMode.Repeated, TileMode.Repeated)) }
    return drawWithContent {
        drawContent()
        drawRect(brush, alpha = alpha)
    }
}

/** Wraps the whole app. */
@Composable
fun PathwaysTheme(content: @Composable () -> Unit) {
    MaterialTheme(colorScheme = CaseFile, typography = PathwaysType, shapes = PathwaysShapes) {
        Box(Modifier.fillMaxSize().paperGrain(GRAIN_ALPHA)) { content() }
    }
}
