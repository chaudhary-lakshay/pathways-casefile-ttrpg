/**
 * The app's design system: a chosen colour scheme, one type scale, one shape
 * scale.
 *
 * The colour schemes themselves live in [ThemeSchemes], which is GENERATED by
 * `tools/gen_theme.py` from Google's own material-color-utilities. This file
 * only chooses between them and applies the user's preferences on top.
 *
 * Why generated rather than hand-picked
 * -------------------------------------
 * The palette this replaces was 30 hex constants read off a pixel-art ramp. It
 * was not badly chosen -- 54 of its 56 foreground/background pairs cleared WCAG
 * AA in both modes -- but it set only 33 of Material's ~48 colour roles. The 15
 * it left out (`surfaceBright`, `surfaceDim`, and the whole `*Fixed` family)
 * fall back to Material's BASELINE tokens, which are the stock purple-tinted
 * neutrals. A scheme that never mentioned purple was still serving it to any
 * component that read one of those roles. Generating every role closes that.
 *
 * Why there is a picker at all
 * ----------------------------
 * "I do not like the theme" is not a defect report, and the contrast audit
 * found nothing to fix. A taste complaint that measurement cannot locate is
 * answered by handing over the choice, which is what the popular open-source
 * Material 3 apps do. Hence five presets, three modes, and a true-black option. The default
 * is Wada, Sanzo Wada's combination #269, which the owner chose (2026-10-11).
 *
 * @see ThemeSeed for why the preset list is curated rather than a colour wheel.
 */

// ---------------------------------------------------------------------------
// Preferences
// ---------------------------------------------------------------------------

/** Which scheme to follow, independent of the seed. */
enum class ThemeMode(val label: String) {
    SYSTEM("System"),
    LIGHT("Light"),
    DARK("Dark"),
}

/**
 * Everything the user can change about the theme.
 *
 * Deliberately NOT stored in [SessionStore]. That file is a per-character
 * play-state journal keyed by sheet name; a display preference belongs to the
 * installation, not to a character, and putting it there would have every save
 * entry carry a copy that could disagree with the others.
 */
data class ThemePrefs(
    val seed: ThemeSeed = ThemeSeed.WADA,
    val mode: ThemeMode = ThemeMode.SYSTEM,
    /** Material You, from the wallpaper. Android 12+ only; see [schemeFor]. */
    val dynamic: Boolean = false,
    /** Pure black surfaces in dark mode, for OLED panels. */
    val amoled: Boolean = false,
    /** A verdict's sound ([RollFlourish]); its motion follows the system's animation setting. */
    val sounds: Boolean = true,
)

private const val PREFS = "pathways.theme"

/** Reads the stored preferences, falling back to the defaults for anything unset. */
fun loadThemePrefs(context: Context): ThemePrefs {
    val p = context.getSharedPreferences(PREFS, Context.MODE_PRIVATE)
    // Stored by NAME, not by ordinal: reordering the enum must not silently
    // repaint every installation. An unknown name means the preset was removed,
    // so fall back rather than throw.
    val seed = p.getString("seed", null)
        ?.let { name -> ThemeSeed.entries.firstOrNull { it.name == name } }
        ?: ThemePrefs().seed
    val mode = p.getString("mode", null)
        ?.let { name -> ThemeMode.entries.firstOrNull { it.name == name } }
        ?: ThemePrefs().mode
    return ThemePrefs(
        seed = seed,
        mode = mode,
        dynamic = p.getBoolean("dynamic", false),
        amoled = p.getBoolean("amoled", false),
        sounds = p.getBoolean("sounds", true),
    )
}

fun saveThemePrefs(context: Context, prefs: ThemePrefs) {
    context.getSharedPreferences(PREFS, Context.MODE_PRIVATE).edit()
        .putString("seed", prefs.seed.name)
        .putString("mode", prefs.mode.name)
        .putBoolean("dynamic", prefs.dynamic)
        .putBoolean("amoled", prefs.amoled)
        .putBoolean("sounds", prefs.sounds)
        .apply()
}

/**
 * Theme state that survives recomposition, read from disk once.
 *
 * ponytail: a plain `MutableState` rather than a ViewModel. The app has one
 * activity, and the durable copy is the SharedPreferences write.
 */
@Composable
fun rememberThemePrefs(): MutableState<ThemePrefs> {
    val context = LocalContext.current
    return remember { mutableStateOf(loadThemePrefs(context)) }
}

// ---------------------------------------------------------------------------
// Scheme selection
// ---------------------------------------------------------------------------

/** True when [ThemePrefs.mode] resolves to the dark scheme right now. */
@Composable
fun ThemePrefs.isDark(): Boolean = when (mode) {
    ThemeMode.SYSTEM -> isSystemInDarkTheme()
    ThemeMode.LIGHT -> false
    ThemeMode.DARK -> true
}

/** Material You is a platform feature and only exists from Android 12. */
val isDynamicColorAvailable: Boolean = Build.VERSION.SDK_INT >= Build.VERSION_CODES.S

/**
 * The scheme to render with.
 *
 * Dynamic colour is applied to the NEUTRALS AND PRIMARY ONLY. The wallpaper
 * scheme's `secondary` and `tertiary` are derived from one hue, so taking them
 * whole would render three of this app's four action categories -- Beyonder
 * material, management, and combat -- as three shades of the same colour. The
 * preset's accents are copied back over the top so the categories survive.
 *
 * That is a weaker guarantee than a preset gives: the wallpaper's primary can
 * still land on the preset's arcane purple, and nothing here can stop it. The
 * preset list is separation-checked at generation time; this path cannot be.
 */
private fun schemeFor(context: Context, prefs: ThemePrefs, dark: Boolean): ColorScheme {
    val preset = if (dark) prefs.seed.dark else prefs.seed.light
    val base = when {
        !prefs.dynamic || !isDynamicColorAvailable -> preset
        dark -> dynamicDarkColorScheme(context).withAccentsOf(preset)
        else -> dynamicLightColorScheme(context).withAccentsOf(preset)
    }
    return if (dark && prefs.amoled) base.asTrueBlack() else base
}

/** Keeps this app's category accents while adopting another scheme's neutrals. */
private fun ColorScheme.withAccentsOf(preset: ColorScheme): ColorScheme = copy(
    secondary = preset.secondary,
    onSecondary = preset.onSecondary,
    secondaryContainer = preset.secondaryContainer,
    onSecondaryContainer = preset.onSecondaryContainer,
    tertiary = preset.tertiary,
    onTertiary = preset.onTertiary,
    tertiaryContainer = preset.tertiaryContainer,
    onTertiaryContainer = preset.onTertiaryContainer,
    error = preset.error,
    onError = preset.onError,
    errorContainer = preset.errorContainer,
    onErrorContainer = preset.onErrorContainer,
)

/**
 * Drops the page to pure black without flattening the elevation stack.
 *
 * Only the roles that cover a whole screen go to black. The `surfaceContainer`
 * ramp is left alone on purpose: blacking that out too would erase the boundary
 * between a card and the page behind it, and these screens are almost entirely
 * cards.
 */
private fun ColorScheme.asTrueBlack(): ColorScheme = copy(
    background = Color.Black,
    surface = Color.Black,
    surfaceDim = Color.Black,
    surfaceContainerLowest = Color.Black,
)

